
-- =============================================================================
-- Project: Battery Pack & Module Manufacturing Execution System (CellMES)
-- File:    schema_definition.sql
-- Dialect: PostgreSQL 13+
-- Author:  Engineering Team
-- =============================================================================
-- PURPOSE:
--   This Data Definition Language (DDL) script provisions the complete schema 
--   for the Battery Pack & Module Manufacturing Execution System (MES). It 
--   manages end-to-end traceability, shop-floor execution, inspection records,
--   and master configurations for electric vehicle (EV) battery production.
--
-- ARCHITECTURAL OVERVIEW:
--   1. Master Configurations:
--      Manages baseline specifications for cell chemistries, module/BMS 
--      variants, pack configurations, user authorizations, and defect taxonomies.
--
--   2. Work Order Execution:
--      Maintains operational lifecycles (SCHEDULED, STARTED, REWORKED, HOLD, 
--      COMPLETED) for both module sub-assemblies (`cellmess_app_module_wo`) and 
--      final battery pack integrations (`cellmes_app_pack_wo`), including Kafka 
--      stream synchronization markers.
--
--   3. Component Traceability & Assembly (Genealogy):
--      Captures 1-to-1 and 1-to-many physical marriages between battery packs, 
--      BMS identifiers, Left-Hand (LH) modules, and Right-Hand (RH) modules 
--      across standard MES flows (`cellmes_app_lhrl_scan`) and external/manual 
--      lines (`cellmes_app_lhrh_scan_nonmes`).
--
--   4. Station Quality Gates & Serialization:
--      Maintains cycle metrics, raw parameter logs, and pass/fail states for:
--        - Pressure Drop Leak Testing (`cellmes_app_leaktest`)
--        - Pre-End of Line (Pre-EOL) High-Voltage Verification (`cellmes_app_pre_eol`)
--        - End-of-Line / Chroma Electrical & Thermal Characterization (`cellmes_app_eol`)
--        - Pre-Delivery Inspection / Final Quality Gate (`cellmes_pdi_station`)
--        - Non-Conformance & Rework Clearance Workflow (`cellmes_app_nc_clearance`)
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. EXTENSIONS & CUSTOM DOMAIN TYPES (ENUMS)
-- =============================================================================

DO $$ BEGIN
    CREATE TYPE public.final_result AS ENUM ('PASS', 'FAIL');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE public.cell_type AS ENUM ('BAK', 'LG', 'OLA');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE public.wo_status AS ENUM ('SCHEDULED', 'STARTED', 'REWORKED', 'HOLD', 'COMPLETED');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE public.active_status_battery AS ENUM ('ACTIVE', 'INACTIVE');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE public.nc_station_id AS ENUM ('LEAK_TEST', 'PRE_EOL', 'EOL', 'PDI');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =============================================================================
-- 2. USER ACCESS CONTROL & MASTER CONFIGURATION TABLES
-- =============================================================================

-- RBAC Group Master
