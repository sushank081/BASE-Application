-- Station 4: Pre-Delivery Inspection (PDI) / Final Mechanical Gate
CREATE TABLE IF NOT EXISTS public.cellmes_pdi_station
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    pack_id           BIGINT NOT NULL,
    leak_test_status  VARCHAR(10) NOT NULL,
